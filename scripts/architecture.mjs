// Rebuild the module dependency view from actual local ESM imports.
import { readFile, writeFile, readdir } from "node:fs/promises";
import { basename } from "node:path";
const files = (await readdir("src")).filter((f) => f.endsWith(".js")).sort();
const notes = {
  app: "Состояние интерфейса, поиск, выбор номера и тарифа, подтверждение и отмена демо-брони.",
  data: "Иллюстративные санатории, координаты, категории номеров, физические номера и тарифы.",
  domain:
    "Проверка дат, пересечения бронирований, вместимость, расчёт стоимости, выделение номера.",
  map: "Leaflet: подложка OpenStreetMap, метки цен, выбор санатория, обработка ошибок карты.",
  storage: "Чтение, проверка и сохранение демо-бронирований в localStorage.",
};
const ids = new Set(files.map((f) => basename(f, ".js")));
const parts = [
  "// GENERATED by npm run arch:sync from src/*.js imports. Do not edit.",
  "specification {",
  "  element module",
  "}",
  "model {",
];
for (const file of files) {
  const id = basename(file, ".js");
  if (!/^[a-zA-Z_][a-zA-Z_0-9]*$/.test(id))
    throw new Error(`Unsupported module name: ${id}`);
  parts.push(
    `  ${id} = module '${file}' {`,
    `    description '${notes[id] || "Модуль проекта"} Исходник: src/${file}'`,
    `    link https://github.com/bekasyl00/Hotel_Business/blob/main/src/${file} 'Исходный код'`,
    "  }",
  );
}
for (const file of files) {
  const source = await readFile(`src/${file}`, "utf8");
  for (const match of source.matchAll(/from\s+['"]\.\/([^'"]+)['"]/g)) {
    const dependency = basename(match[1], ".js");
    if (!ids.has(dependency))
      throw new Error(`Missing local dependency ${match[1]}`);
    parts.push(`  ${basename(file, ".js")} -> ${dependency} 'import'`);
  }
}
parts.push(
  "}",
  "views {",
  "  view modules {",
  "    title 'Реализовано: модули JavaScript'",
  "    description 'Автоматически построено из импортов src/*.js. Откройте компонент, чтобы перейти к исходнику.'",
  `    include ${[...ids].join(", ")}`,
  "  }",
  "}",
  "",
);
await writeFile("architecture/modules.c4", parts.join("\n"));
console.log(`Architecture synchronized: ${files.length} real source modules.`);
